    private void jTable3MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable3MouseClicked
        int fila = jTable3.getSelectedRow();
        if (fila >= 0) {
            String id = jTable3.getValueAt(fila, 0).toString();
            Empresa e = sistema.buscarEmpresaPorIdentificador(id);

            if (e != null) {
                jTextField1.setText(e.getIdentificador());
                jTextField2.setText(e.getNombre());
                jTextField5.setText(e.getCorreo());
                jTextField8.setText(e.getTelefono());
                jTextField6.setText(e.getSector());
                jTextField9.setText(e.getDireccion());
                jTextField7.setText(e.getSitioWeb());
                jTextField10.setText(e.getDescripcionEmpresa());

                javax.swing.table.DefaultTableModel modeloOfertas = (javax.swing.table.DefaultTableModel) jTable2.getModel();
                modeloOfertas.setRowCount(0);
                for (OfertaLaboral oferta : e.getOfertas()) {
                    modeloOfertas.addRow(new Object[]{oferta.getId(), oferta.getCargo(), oferta.getModalidad(), oferta.getSalario()});
                }
            }
        }
    }//GEN-LAST:event_jTable3MouseClicked

