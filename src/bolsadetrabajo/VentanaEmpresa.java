    private void cargarTablaEmpresas() {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable3.getModel();
        modelo.setRowCount(0); 

        ArrayList<Empresa> lista = sistema.obtenerTodasLasEmpresas();
        if (lista != null) {
            for (Empresa e : lista) {
                modelo.addRow(new Object[]{
                    e.getIdentificador(),
                    e.getNombre(),
                    e.getSector(),
                    e.getCorreo(),
                    e.getSitioWeb(),
                    e.getTelefono()
                });
            }
        }
    }
