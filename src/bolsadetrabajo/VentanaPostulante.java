    private void cargarTablaPostulantes() {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0); 

        ArrayList<Trabajador> lista = Sistema.getTrabajadores();
        if (lista != null) {
            for (Trabajador t : lista) {
                modelo.addRow(new Object[]{
                t.getIdentificador(),
                t.getNombre(),
                t.getCorreo(),
                t.getTelefono(),
                t.getEdad(),
                t.getSexo(),
                t.getProfesion(),
                t.getAnyosExperiencia()
                });
            }
        }
    }

    

    
