    private void BuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BuscarActionPerformed
        // TODO add your handling code here:
        String idBuscado = jTextField16.getText();
        if (idBuscado.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese un ID para buscar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        Trabajador TrabajadorB = Sistema.retornarTrabajador(idBuscado);
        if (TrabajadorB != null)
        {
            jTextField1.setText(TrabajadorB.getIdentificador());
            jTextField2.setText(TrabajadorB.getNombre());
            jTextField3.setText(TrabajadorB.getCorreo());
            jTextField4.setText(TrabajadorB.getProfesion());
            jTextField5.setText(String.valueOf(TrabajadorB.getAnyosExperiencia()));
            jTextField6.setText(String.valueOf(TrabajadorB.getEdad()));
            jTextField7.setText(TrabajadorB.getTelefono());
            jComboBox1.setSelectedItem(TrabajadorB.getSexo());
            
        }

    }//GEN-LAST:event_BuscarActionPerformed

